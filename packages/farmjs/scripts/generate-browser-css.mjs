import fs from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const cssPath = require.resolve("@farming-labs/theme/browser/css");
const outputPath = fileURLToPath(new URL("../src/browser-css.generated.ts", import.meta.url));
const css = fs.readFileSync(cssPath, "utf8");
const source = `// Generated by scripts/generate-browser-css.mjs. Do not edit.\nconst farmDocsBrowserCss = ${JSON.stringify(css)};\n\nexport default farmDocsBrowserCss;\n`;

if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== source) {
  fs.writeFileSync(outputPath, source);
}
