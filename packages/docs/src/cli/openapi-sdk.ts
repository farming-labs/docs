import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import pc from "picocolors";
import {
  buildNormalizedOpenApiModel,
  type NormalizedOpenApiMediaType,
  type NormalizedOpenApiOperation,
  type NormalizedOpenApiParameter,
  type NormalizedOpenApiResponse,
} from "../openapi-operations.js";
import { displayOpenApiCliSource, loadOpenApiCliSource } from "./openapi-source.js";

export interface OpenApiSdkOptions {
  source?: string;
  output?: string;
  clientName?: string;
  baseUrl?: string;
  sourceBaseUrl?: string;
  check: boolean;
  dryRun: boolean;
  force: boolean;
  help: boolean;
  rootDir?: string;
}

export interface OpenApiSdkReport {
  format: "farming-labs-openapi-sdk.v1";
  source: string;
  output: string;
  clientName: string;
  operationCount: number;
  schemaCount: number;
  changed: boolean;
  wrote: boolean;
}

interface TypeScriptSchemaContext {
  document: Record<string, unknown>;
  referenceNames: Map<string, string>;
  references: Set<string>;
}

interface GeneratedOperationNames {
  methodName: string;
  inputName: string;
  responseName: string;
}

interface ComponentSchema {
  name: string;
  reference: string;
  schema: unknown;
}

const GENERATED_SDK_MARKER = "// Generated by @farming-labs/docs openapi sdk. Do not edit.";
const GENERATED_TYPE_NAMES = new Set(["ApiClientOptions", "ApiError", "ApiResponse"]);
const RESERVED_METHOD_NAMES = new Set(["constructor"]);

export function parseOpenApiSdkArgs(argv: string[]): OpenApiSdkOptions {
  const positionals: string[] = [];
  let source: string | undefined;
  let output: string | undefined;
  let clientName: string | undefined;
  let baseUrl: string | undefined;
  let sourceBaseUrl: string | undefined;
  let check = false;
  let dryRun = false;
  let force = false;
  let help = false;

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index] ?? "";
    if (argument === "--help" || argument === "-h") {
      help = true;
      continue;
    }
    if (argument === "--check") {
      check = true;
      continue;
    }
    if (argument === "--dry-run") {
      dryRun = true;
      continue;
    }
    if (argument === "--force") {
      force = true;
      continue;
    }
    if (!argument.startsWith("--")) {
      positionals.push(argument);
      continue;
    }

    const separator = argument.indexOf("=");
    const flag = argument.slice(2, separator === -1 ? undefined : separator);
    const inlineValue = separator === -1 ? undefined : argument.slice(separator + 1);
    const value = inlineValue ?? argv[index + 1];
    if (value === undefined || value.startsWith("--")) {
      throw new Error(`Missing value for --${flag}.`);
    }
    if (inlineValue === undefined) index += 1;

    if (flag === "source") source = value;
    else if (flag === "output" || flag === "out") output = value;
    else if (flag === "client-name" || flag === "name") clientName = value;
    else if (flag === "base-url") baseUrl = value;
    else if (flag === "source-base-url") sourceBaseUrl = value;
    else throw new Error(`Unknown OpenAPI SDK option: --${flag}.`);
  }

  for (const positional of positionals) {
    if (!source) source = positional;
    else throw new Error("Pass exactly one OpenAPI source.");
  }
  if (check && dryRun) throw new Error("Use either --check or --dry-run, not both.");
  if (!help && !source) throw new Error("Pass an OpenAPI source.");
  if (!help && !output) throw new Error("Pass --output <path> for the generated TypeScript SDK.");

  return {
    source,
    output,
    clientName,
    baseUrl,
    sourceBaseUrl,
    check,
    dryRun,
    force,
    help,
  };
}

export async function runOpenApiSdk(options: OpenApiSdkOptions): Promise<OpenApiSdkReport> {
  if (!options.source || !options.output) {
    throw new Error("OpenAPI SDK source and output are required.");
  }
  const rootDir = path.resolve(options.rootDir ?? process.cwd());
  const outputPath = resolveOutputPath(rootDir, options.output);
  const document = await loadOpenApiCliSource(options.source, {
    rootDir,
    baseUrl: options.sourceBaseUrl,
  });
  const model = buildNormalizedOpenApiModel(document);
  const clientName = normalizeTypeName(options.clientName ?? `${model.title} Client`);
  const code = generateOpenApiTypeScriptSdk(document, {
    clientName,
    baseUrl: options.baseUrl,
    source: displayOpenApiCliSource(options.source),
  });
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf-8") : undefined;
  const changed = current !== code;
  const report: OpenApiSdkReport = {
    format: "farming-labs-openapi-sdk.v1",
    source: displayOpenApiCliSource(options.source),
    output: normalizeRelativePath(path.relative(rootDir, outputPath)),
    clientName,
    operationCount: model.operationCount,
    schemaCount: collectComponentSchemas(document).length,
    changed,
    wrote: false,
  };

  if (options.dryRun) {
    console.log(code);
    return report;
  }
  if (options.check) {
    if (changed) {
      console.error(
        pc.red(
          `${report.output} is missing or stale. Run docs openapi sdk ${options.source} --output ${options.output}.`,
        ),
      );
      process.exitCode = 1;
    } else {
      console.log(pc.green(`${report.output} is up to date.`));
    }
    return report;
  }
  if (current !== undefined && !current.startsWith(GENERATED_SDK_MARKER) && !options.force) {
    throw new Error(
      `Refusing to replace non-generated file ${report.output}. Pass --force only after reviewing that file.`,
    );
  }

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, code, "utf-8");
  report.wrote = true;
  console.log(
    pc.green(
      `${changed ? "Generated" : "Refreshed"} ${report.output} with ${report.operationCount} operation${report.operationCount === 1 ? "" : "s"} and ${report.schemaCount} schema${report.schemaCount === 1 ? "" : "s"}.`,
    ),
  );
  return report;
}

export function generateOpenApiTypeScriptSdk(
  document: Record<string, unknown>,
  options: { clientName?: string; baseUrl?: string; source?: string } = {},
): string {
  const model = buildNormalizedOpenApiModel(document);
  const usedTypeNames = new Set(GENERATED_TYPE_NAMES);
  const clientName = claimName(
    normalizeTypeName(options.clientName ?? `${model.title} Client`),
    usedTypeNames,
  );
  const components = collectComponentSchemas(document, usedTypeNames);
  const referenceNames = new Map(
    components.map((component) => [component.reference, component.name]),
  );
  const operationNames = new Map<NormalizedOpenApiOperation, GeneratedOperationNames>();
  const usedMethodNames = new Set<string>();
  for (const operation of model.operations) {
    const baseName = normalizeTypeName(operation.operationId);
    operationNames.set(operation, {
      methodName: claimName(normalizeMethodName(operation.operationId), usedMethodNames),
      inputName: claimName(`${baseName}Input`, usedTypeNames),
      responseName: claimName(`${baseName}Response`, usedTypeNames),
    });
  }

  const schemaContext: TypeScriptSchemaContext = {
    document,
    referenceNames,
    references: new Set(),
  };
  const defaultBaseUrl = resolveSdkBaseUrl(options.baseUrl, model.servers);
  const lines: string[] = [
    GENERATED_SDK_MARKER,
    `// Source: ${sanitizeLineComment(options.source ?? "OpenAPI contract")}`,
    "",
    "export interface ApiClientOptions {",
    "  baseUrl?: string;",
    "  fetch?: typeof fetch;",
    "  headers?: HeadersInit;",
    "}",
    "",
    "export interface ApiResponse<TStatus extends number | string, TData> {",
    "  status: TStatus;",
    "  data: TData;",
    "  headers: Headers;",
    "}",
    "",
    "export class ApiError<TData = unknown> extends Error {",
    "  readonly status: number;",
    "  readonly data: TData;",
    "  readonly headers: Headers;",
    "",
    "  constructor(status: number, data: TData, headers: Headers) {",
    "    super(`API request failed with status ${status}.`);",
    '    this.name = "ApiError";',
    "    this.status = status;",
    "    this.data = data;",
    "    this.headers = headers;",
    "  }",
    "}",
  ];

  for (const component of components) {
    lines.push(
      "",
      `export type ${component.name} = ${schemaToTypeScript(component.schema, schemaContext)};`,
    );
  }

  for (const operation of model.operations) {
    const names = operationNames.get(operation)!;
    lines.push("", ...renderOperationTypes(operation, names, schemaContext));
  }

  lines.push(
    "",
    `const DEFAULT_BASE_URL = ${JSON.stringify(defaultBaseUrl)};`,
    "",
    "function joinUrl(baseUrl: string, pathname: string): string {",
    '  return `${baseUrl.replace(/\\/+$/, "")}/${pathname.replace(/^\\/+/, "")}`;',
    "}",
    "",
    "function appendQueryParameter(searchParams: URLSearchParams, name: string, value: unknown): void {",
    "  if (value === undefined || value === null) return;",
    "  if (Array.isArray(value)) {",
    "    for (const entry of value) appendQueryParameter(searchParams, name, entry);",
    "    return;",
    "  }",
    '  searchParams.append(name, typeof value === "object" ? JSON.stringify(value) : String(value));',
    "}",
    "",
    "async function parseApiResponse(response: Response): Promise<unknown> {",
    "  if (response.status === 204 || response.status === 205) return undefined;",
    '  const contentLength = response.headers.get("content-length");',
    '  if (contentLength === "0") return undefined;',
    '  const contentType = response.headers.get("content-type")?.toLowerCase() ?? "";',
    '  if (contentType.includes("json") || contentType.includes("+json")) return response.json();',
    "  return response.text();",
    "}",
    "",
    `export class ${clientName} {`,
    "  private readonly baseUrl: string;",
    "  private readonly fetchImpl: typeof fetch;",
    "  private readonly defaultHeaders: Headers;",
    "",
    "  constructor(options: ApiClientOptions = {}) {",
    "    this.baseUrl = options.baseUrl ?? DEFAULT_BASE_URL;",
    "    if (!this.baseUrl) {",
    '      throw new Error("A baseUrl is required because the OpenAPI contract has no absolute server URL.");',
    "    }",
    "    this.fetchImpl = options.fetch ?? globalThis.fetch.bind(globalThis);",
    "    this.defaultHeaders = new Headers(options.headers);",
    "  }",
  );
  for (const operation of model.operations) {
    lines.push("", ...renderOperationMethod(operation, operationNames.get(operation)!));
  }
  lines.push("}", "");
  return lines.join("\n");
}

