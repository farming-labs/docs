function renderOperationTypes(
  operation: NormalizedOpenApiOperation,
  names: GeneratedOperationNames,
  context: TypeScriptSchemaContext,
): string[] {
  const lines = [`export interface ${names.inputName} {`];
  for (const location of ["path", "query", "header", "cookie"] as const) {
    const parameters = operation.parameters.filter((parameter) => parameter.in === location);
    if (parameters.length === 0) continue;
    const required = parameters.some((parameter) => parameter.required);
    lines.push(
      `  ${location}${required ? "" : "?"}: ${renderParameterObject(parameters, context)};`,
    );
  }
  if (operation.requestBody) {
    const media = selectMediaType(operation.requestBody.content);
    lines.push(
      `  body${operation.requestBody.required ? "" : "?"}: ${schemaToTypeScript(media?.schema, context)};`,
    );
  }
  lines.push(
    '  request?: Omit<RequestInit, "method" | "body" | "headers"> & { headers?: HeadersInit };',
    "}",
    "",
    `export type ${names.responseName} = ${renderResponseType(operation.responses, context)};`,
  );
  return lines;
}

function renderOperationMethod(
  operation: NormalizedOpenApiOperation,
  names: GeneratedOperationNames,
): string[] {
  const inputRequired =
    operation.parameters.some((parameter) => parameter.required) ||
    operation.requestBody?.required === true;
  const lines = [
    `  async ${names.methodName}(input: ${names.inputName}${inputRequired ? "" : " = {}"}): Promise<${names.responseName}> {`,
    `    let operationPath = ${JSON.stringify(operation.path)};`,
  ];
  for (const parameter of operation.parameters.filter((entry) => entry.in === "path")) {
    lines.push(
      `    operationPath = operationPath.replaceAll(${JSON.stringify(`{${parameter.name}}`)}, encodeURIComponent(String(input.path[${JSON.stringify(parameter.name)}])));`,
    );
  }
  lines.push("    const url = new URL(joinUrl(this.baseUrl, operationPath));");
  for (const parameter of operation.parameters.filter((entry) => entry.in === "query")) {
    lines.push(
      `    appendQueryParameter(url.searchParams, ${JSON.stringify(parameter.name)}, input.query?.[${JSON.stringify(parameter.name)}]);`,
    );
  }
  lines.push("    const headers = new Headers(this.defaultHeaders);");
  for (const parameter of operation.parameters.filter((entry) => entry.in === "header")) {
    lines.push(
      `    if (input.header?.[${JSON.stringify(parameter.name)}] !== undefined) headers.set(${JSON.stringify(parameter.name)}, String(input.header[${JSON.stringify(parameter.name)}]));`,
    );
  }
  const cookieParameters = operation.parameters.filter((entry) => entry.in === "cookie");
  if (cookieParameters.length > 0) {
    lines.push("    const cookieParts: string[] = [];");
    for (const parameter of cookieParameters) {
      lines.push(
        `    if (input.cookie?.[${JSON.stringify(parameter.name)}] !== undefined) cookieParts.push(${JSON.stringify(`${parameter.name}=`)} + encodeURIComponent(String(input.cookie[${JSON.stringify(parameter.name)}])));`,
      );
    }
    lines.push('    if (cookieParts.length > 0) headers.set("cookie", cookieParts.join("; "));');
  }
  lines.push(
    "    const requestHeaders = new Headers(input.request?.headers);",
    "    requestHeaders.forEach((value, name) => headers.set(name, value));",
    "    const requestOptions = { ...input.request };",
    "    delete requestOptions.headers;",
  );
  const requestMedia = operation.requestBody
    ? selectMediaType(operation.requestBody.content)
    : undefined;
  if (operation.requestBody) {
    if (requestMedia?.mediaType.includes("json") || requestMedia?.mediaType.includes("+json")) {
      lines.push(
        `    headers.set("content-type", ${JSON.stringify(requestMedia.mediaType)});`,
        "    const body = input.body === undefined ? undefined : JSON.stringify(input.body);",
      );
    } else {
      if (requestMedia) {
        lines.push(`    headers.set("content-type", ${JSON.stringify(requestMedia.mediaType)});`);
      }
      lines.push("    const body = input.body as BodyInit | null | undefined;");
    }
  } else {
    lines.push("    const body = undefined;");
  }
  lines.push(
    "    const response = await this.fetchImpl(url, {",
    "      ...requestOptions,",
    `      method: ${JSON.stringify(operation.method)},`,
    "      headers,",
    "      body,",
    "    });",
    "    const data = await parseApiResponse(response);",
    "    if (!response.ok) throw new ApiError(response.status, data, response.headers);",
    `    return { status: response.status, data, headers: response.headers } as ${names.responseName};`,
    "  }",
  );
  return lines;
}

function renderParameterObject(
  parameters: NormalizedOpenApiParameter[],
  context: TypeScriptSchemaContext,
): string {
  return `{ ${parameters
    .map(
      (parameter) =>
        `${JSON.stringify(parameter.name)}${parameter.required ? "" : "?"}: ${schemaToTypeScript(parameter.schema, context)}`,
    )
    .join("; ")} }`;
}

function renderResponseType(
  responses: NormalizedOpenApiResponse[],
  context: TypeScriptSchemaContext,
): string {
  const successful = responses.filter(
    (response) => /^2\d\d$/.test(response.status) || /^2XX$/i.test(response.status),
  );
  const candidates =
    successful.length > 0
      ? successful
      : responses.filter((response) => response.status === "default");
  if (candidates.length === 0) return "ApiResponse<number, unknown>";
  return candidates
    .map((response) => {
      const media = selectMediaType(response.content);
      const data = media ? schemaToTypeScript(media.schema, context) : "undefined";
      const status = /^\d+$/.test(response.status) ? response.status : "number";
      return `ApiResponse<${status}, ${data}>`;
    })
    .join(" | ");
}

function selectMediaType(
  mediaTypes: NormalizedOpenApiMediaType[],
): NormalizedOpenApiMediaType | undefined {
  return (
    mediaTypes.find((entry) => entry.mediaType === "application/json") ??
    mediaTypes.find((entry) => entry.mediaType.includes("+json")) ??
    mediaTypes[0]
  );
}

function collectComponentSchemas(
  document: Record<string, unknown>,
  usedNames = new Set<string>(),
): ComponentSchema[] {
  const components = asRecord(document.components);
  const componentSchemas = asRecord(components?.schemas) ?? {};
  const definitions = asRecord(document.definitions) ?? {};
  const schemas: ComponentSchema[] = [];
  for (const [prefix, entries] of [
    ["#/components/schemas", componentSchemas],
    ["#/definitions", definitions],
  ] as const) {
    for (const key of Object.keys(entries).sort()) {
      schemas.push({
        name: claimName(normalizeTypeName(key), usedNames),
        reference: `${prefix}/${escapeJsonPointer(key)}`,
        schema: entries[key],
      });
    }
  }
  return schemas;
}

function schemaToTypeScript(schema: unknown, context: TypeScriptSchemaContext): string {
  if (schema === undefined || schema === true) return "unknown";
  if (schema === false) return "never";
  const record = asRecord(schema);
  if (!record) return "unknown";

  const reference = typeof record.$ref === "string" ? record.$ref : undefined;
  if (reference) {
    const named = context.referenceNames.get(reference);
    if (named) return named;
    if (!context.references.has(reference) && reference.startsWith("#/")) {
      const target = resolvePointer(context.document, reference.slice(1));
      if (target !== undefined) {
        return schemaToTypeScript(target, {
          ...context,
          references: new Set(context.references).add(reference),
        });
      }
    }
    return "unknown";
  }

  if (Object.hasOwn(record, "const")) return literalType(record.const);
  if (Array.isArray(record.enum) && record.enum.length > 0) {
    return record.enum.map(literalType).join(" | ");
  }
  const allOf = schemaArray(record.allOf);
  if (allOf.length > 0) {
    return allOf.map((entry) => parenthesize(schemaToTypeScript(entry, context))).join(" & ");
  }
  const union = [...schemaArray(record.oneOf), ...schemaArray(record.anyOf)];
  if (union.length > 0) {
    return union.map((entry) => schemaToTypeScript(entry, context)).join(" | ");
  }

  const types = normalizeSchemaTypes(record.type);
  let result: string;
  if (types.length > 1) {
    result = types.map((type) => schemaTypeToTypeScript(type, record, context)).join(" | ");
  } else {
    result = schemaTypeToTypeScript(types[0], record, context);
  }
  if (record.nullable === true && !result.split(" | ").includes("null")) result += " | null";
  return result;
}

function schemaTypeToTypeScript(
  type: string | undefined,
  schema: Record<string, unknown>,
  context: TypeScriptSchemaContext,
): string {
  if (type === "string") return schema.format === "binary" ? "Blob" : "string";
  if (type === "integer" || type === "number") return "number";
  if (type === "boolean") return "boolean";
  if (type === "null") return "null";
  if (type === "array" || schema.items !== undefined) {
    return `Array<${schemaToTypeScript(schema.items, context)}>`;
  }
  const properties = asRecord(schema.properties);
  if (type === "object" || properties || schema.additionalProperties !== undefined) {
    const required = new Set(stringArray(schema.required));
    const fields = Object.keys(properties ?? {})
      .sort()
      .map(
        (name) =>
          `${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${schemaToTypeScript(properties?.[name], context)}`,
      );
    const objectType = fields.length > 0 ? `{ ${fields.join("; ")} }` : "Record<string, never>";
    const additional = schema.additionalProperties;
    if (additional === false) return objectType;
    const additionalType =
      additional === undefined || additional === true
        ? "unknown"
        : schemaToTypeScript(additional, context);
    if (fields.length === 0) return `Record<string, ${additionalType}>`;
    return `${parenthesize(objectType)} & Record<string, ${additionalType}>`;
  }
  return "unknown";
}

function resolveSdkBaseUrl(override: string | undefined, servers: string[]): string {
  if (override) return override;
  for (const server of servers) {
    try {
      const url = new URL(server);
      if (url.protocol === "http:" || url.protocol === "https:") return url.href.replace(/\/$/, "");
    } catch {
      // Relative and templated servers require an explicit runtime base URL.
    }
  }
  return "";
}

function resolveOutputPath(rootDir: string, output: string): string {
  const outputPath = path.resolve(rootDir, output);
  if (!isPathInside(rootDir, outputPath)) {
    throw new Error("OpenAPI SDK output must be a file inside the project root.");
  }

  let existingAncestor = outputPath;
  while (!existsSync(existingAncestor)) {
    const parent = path.dirname(existingAncestor);
    if (parent === existingAncestor) break;
    existingAncestor = parent;
  }
  if (!isPathInside(realpathSync(rootDir), realpathSync(existingAncestor), true)) {
    throw new Error("OpenAPI SDK output must not escape the project root through a symlink.");
  }
  return outputPath;
}

function isPathInside(rootDir: string, candidate: string, allowRoot = false): boolean {
  const relative = path.relative(rootDir, candidate);
  return (
    (allowRoot || relative.length > 0) &&
    relative !== ".." &&
    !relative.startsWith(`..${path.sep}`) &&
    !path.isAbsolute(relative)
  );
}

function normalizeTypeName(value: string): string {
  const parts = value.match(/[A-Za-z0-9]+/g) ?? [];
  const name = parts.map((part) => `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`).join("");
  const normalized = name || "ApiClient";
  return /^\d/.test(normalized) ? `_${normalized}` : normalized;
}

function normalizeMethodName(value: string): string {
  const typeName = normalizeTypeName(value);
  const methodName = `${typeName[0]?.toLowerCase() ?? "a"}${typeName.slice(1)}`;
  return RESERVED_METHOD_NAMES.has(methodName) ? `${methodName}Operation` : methodName;
}

function claimName(base: string, used: Set<string>): string {
  let candidate = base;
  let suffix = 2;
  while (used.has(candidate)) {
    candidate = `${base}${suffix}`;
    suffix += 1;
  }
  used.add(candidate);
  return candidate;
}

function normalizeSchemaTypes(value: unknown): string[] {
  if (typeof value === "string") return [value];
  return Array.isArray(value)
    ? value.filter((entry): entry is string => typeof entry === "string")
    : [];
}

function schemaArray(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

function stringArray(value: unknown): string[] {
  return Array.isArray(value)
    ? value.filter((entry): entry is string => typeof entry === "string")
    : [];
}

function literalType(value: unknown): string {
  return typeof value === "string" ||
    typeof value === "number" ||
    typeof value === "boolean" ||
    value === null
    ? JSON.stringify(value)
    : "unknown";
}

function parenthesize(value: string): string {
  return value.includes(" | ") || value.includes(" & ") ? `(${value})` : value;
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  return value && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : undefined;
}

function resolvePointer(document: Record<string, unknown>, pointer: string): unknown {
  let current: unknown = document;
  for (const token of pointer.slice(1).split("/")) {
    const record = asRecord(current);
    if (!record) return undefined;
    current = record[token.replaceAll("~1", "/").replaceAll("~0", "~")];
  }
  return current;
}

function escapeJsonPointer(value: string): string {
  return value.replaceAll("~", "~0").replaceAll("/", "~1");
}

function normalizeRelativePath(value: string): string {
  return value.replaceAll(path.sep, "/");
}

function sanitizeLineComment(value: string): string {
  return value.replace(/[\r\n]+/g, " ");
}
